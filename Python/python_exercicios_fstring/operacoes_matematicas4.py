num1 = int(input("Digite um número inteiro: "))
num2 = int(input("Digite outro número inteiro: "))

soma = num1 + num2
subtração = num1 - num2
multiplicação = num1 * num2
print(f"[num1] + [num2] = [soma] = {soma}")
print(f"[num1] - [num2] = [subtração] = {subtração}")
print(f"[num1] * [num2] = [multiplicação] = {multiplicação}")